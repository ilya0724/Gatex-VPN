def crumbs_html(items):
    out = ['<a href="/">Главная</a>']
    for name, href in items:
        out.append('<span aria-hidden="true">/</span>')
        out.append(f'<a href="{href}">{name}</a>' if href else f"<span>{name}</span>")
    return f'<nav class="crumbs" aria-label="Навигация">{"".join(out)}</nav>'


def crumbs_ld(items):
    elems = [{"@type": "ListItem", "position": 1, "name": "Главная", "item": BASE + "/"}]
    for i, (name, href) in enumerate(items, start=2):
        e = {"@type": "ListItem", "position": i, "name": name}
        if href:
            e["item"] = BASE + href
        elems.append(e)
    return {"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": elems}


def faq_html(items):
    rows = "\n".join(
        f'        <details class="glass"><summary>{q}</summary><p>{a}</p></details>' for q, a in items
    )
    return f'<div class="faq doc-faq">\n{rows}\n      </div>'


def faq_ld(items):
    return {
        "@context": "https://schema.org",
        "@type": "FAQPage",
        "mainEntity": [
            {"@type": "Question", "name": strip_tags(q), "acceptedAnswer": {"@type": "Answer", "text": strip_tags(a)}}
            for q, a in items
        ],
    }


def article_ld(slug, headline, description):
    org = {"@type": "Organization", "name": "GateX VPN", "url": BASE + "/", "logo": BASE + "/apple-touch-icon.png"}
    return {
        "@context": "https://schema.org",
        "@type": "Article",
        "headline": headline,
        "description": description,
        "inLanguage": "ru",
        "mainEntityOfPage": f"{BASE}/{slug}",
        "image": BASE + "/og.png",
        "datePublished": UPDATED,
        "dateModified": UPDATED,
        "author": org,
        "publisher": org,
    }


def toc_html(sections):
    items = "".join(f'<li><a href="#{sid}">{name}</a></li>' for sid, name in sections)
    return f'<nav class="toc glass" aria-label="Содержание"><b>Содержание</b><ol>{items}</ol></nav>'


GUIDES = []  # (slug, short title, card text) for the hub, related blocks and sitemap


def related(current):
    cards = []
    for slug, name, text in GUIDES:
        if slug == current:
            continue
        cards.append(
            f'<a class="feat glass" href="/{slug}"><h3>{name}</h3><p>{text}</p><span class="go">Читать →</span></a>'
        )
    return f"""<section>
    <div class="wrap">
      <div class="sec-head"><span class="eyebrow">Ещё по теме</span><h2>Другие инструкции</h2></div>
      <div class="related">{"".join(cards)}</div>
    </div>
  </section>"""


def guide(slug, *, title, description, h1, lead, crumb, sections, faq, final_title=None):
    """sections: list of (id, toc name, html)."""
    head_cta = f"""<div class="cta">
          <a class="btn btn-primary" href="{BOT}" target="_blank" rel="noopener">{TG}{TRIAL} бесплатно</a>
          <a class="btn btn-glass" href="/#pricing">Тарифы от 49 ₽</a>
        </div>"""
    prose = "\n".join(f'<h2 id="{sid}">{name}</h2>\n{content}' for sid, name, content in sections)
    toc = toc_html([(sid, name) for sid, name, _ in sections] + [("faq", "Частые вопросы")])
    body = f"""  <div class="wrap">
    {crumbs_html([("Инструкции", "/instrukcii/"), (crumb, None)])}
    <article class="doc">
      <header class="doc-head">
        <h1>{h1}</h1>
        <p class="lead">{lead}</p>
        <p class="meta">Обновлено {UPDATED_RU}</p>
        {head_cta}
      </header>
      {toc}
      <div class="prose">
{prose}
<h2 id="faq">Частые вопросы</h2>
      </div>
      {faq_html(faq)}
    </article>
  </div>
  {related(slug)}
  {final_cta(final_title) if final_title else final_cta()}"""
    ld = [
        article_ld(slug, h1, description),
        crumbs_ld([("Инструкции", "/instrukcii/"), (crumb, f"/{slug}")]),
        faq_ld(faq),
    ]
    out = SITE / slug.strip("/") / "index.html"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(page(slug, title, description, body, ld), encoding="utf-8")


def steps(items):
    rows = "".join(
        f'<article class="step glass"><span class="n">{i}</span><h3>{h}</h3><p>{p}</p></article>'
        for i, (h, p) in enumerate(items, start=1)
    )
    return f'<div class="steps in-doc">{rows}</div>'


def note(text, warn=False):
    return f'<div class="note glass{" warn" if warn else ""}"><p>{text}</p></div>'


